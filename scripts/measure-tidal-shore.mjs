// Run with Node and ffmpeg when the arcade recording changes. Only the two outer
// silhouettes at the player's nose are sampled. The browser never decodes pixels for physics.
import {execFileSync} from 'node:child_process';
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {tidalPortalContactAt} from '../web/tidal-cube-intro.js';

const source=new URL('../web/arcade-video/tidal-wave.mp4',import.meta.url);
const output=new URL('../web/tidal-shore-samples.js',import.meta.url);
const width=21,height=500,fps=30,firstFrame=Math.floor(tidalPortalContactAt*fps);
const frameSize=width*height*3;
const pixels=execFileSync('ffmpeg',[
 '-loglevel','error','-i',fileURLToPath(source),'-an','-vf',
 'fps=30,scale=800:500,format=rgb24,crop=21:500:299:0','-f','rawvideo','-threads','1','-'
],{maxBuffer:64*1024*1024});
if(pixels.length%frameSize||pixels.length<=(firstFrame+1)*frameSize)throw Error('Incomplete Tidal Wave video.');

function inset(frame,x,upper){
 // Black video trim connects to the edge of the frame. Surf, blue light and
 // decorations can cross this strip. Require three lit pixels to exit the trim.
 let litRun=0;
 for(let depth=0;depth<38;depth++){
  const y=upper?depth:height-1-depth;
  const i=frame*frameSize+(y*width+x)*3;
  const lit=Math.max(pixels[i],pixels[i+1],pixels[i+2])>14;
  litRun=lit?litRun+1:0;
  if(litRun===3)return depth-2;
 }
 return null;
}
function shore(frames,upper){
 let previous=0;
 const raw=frames.map(frame=>{
  const depths=[];
  for(let x=0;x<width;x++){
   const depth=inset(frame,x,upper);
   if(depth!==null)depths.push(depth);
  }
  // Hold the last visible edge through fades. A few dark columns cannot move
  // the entire floor into open water.
  if(depths.length>=Math.ceil(width*.6)){
   depths.sort((a,b)=>a-b);
   previous=depths[Math.floor((depths.length-1)*.40)];
  }
  return previous;
 });
 return raw.map((value,i)=>{
  const a=raw[Math.max(0,i-1)],b=raw[Math.min(raw.length-1,i+1)];
  return Math.max(Math.min(a,b),Math.min(value,Math.max(a,b)));
 });
}
const count=pixels.length/frameSize-firstFrame;
const frames=Array.from({length:count},(_,i)=>firstFrame+i);
const top=shore(frames,true),bottom=shore(frames,false);
const pairs=frames.map((_,i)=>top[i]+','+bottom[i]);
const lines=[];
for(let i=0;i<count;i+=16)lines.push(' '+pairs.slice(i,i+16).join(', '));
writeFileSync(output,'// Generated by scripts/measure-tidal-shore.mjs. Each pair is the top and bottom\n'+
 '// black silhouette depth in the 800 × 500 playfield at the wave column.\n'+
 'export const shoreFps='+fps+',firstShoreFrame='+firstFrame+';\n'+
 'export const shoreInsets=new Uint8Array([\n'+lines.join(',\n')+'\n]);\n');
